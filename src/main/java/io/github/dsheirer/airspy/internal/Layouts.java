package io.github.dsheirer.airspy.internal;

import static java.lang.foreign.MemoryLayout.PathElement.groupElement;
import static java.lang.foreign.MemoryLayout.paddingLayout;
import static java.lang.foreign.MemoryLayout.sequenceLayout;
import static java.lang.foreign.MemoryLayout.structLayout;
import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_BYTE;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_LONG;

import java.lang.foreign.GroupLayout;
import java.lang.foreign.MemoryLayout;
import java.lang.foreign.MemorySegment;
import java.nio.charset.StandardCharsets;

/**
 * Memory layouts of the structures in {@code airspy.h}.
 *
 * <p>These are written by hand rather than generated by jextract because every
 * field has a fixed width: unlike jextract's {@code uint64_t} mapping, which
 * goes through {@code long} and is wrong on Windows, a single set of layouts is
 * correct on all supported platforms.
 */
public final class Layouts {
    /** {@code airspy_lib_version_t}. */
    public static final GroupLayout LIB_VERSION = structLayout(
        JAVA_INT.withName("major_version"),
        JAVA_INT.withName("minor_version"),
        JAVA_INT.withName("revision"));

    /** {@code airspy_transfer_t}. */
    public static final GroupLayout TRANSFER = structLayout(
        ADDRESS.withName("device"),
        ADDRESS.withName("ctx"),
        ADDRESS.withName("samples"),
        JAVA_INT.withName("sample_count"),
        paddingLayout(ADDRESS.byteSize() - JAVA_INT.byteSize()),
        JAVA_LONG.withName("dropped_samples"),
        JAVA_INT.withName("sample_type"),
        paddingLayout(4));

    /** {@code airspy_read_partid_serialno_t}. */
    public static final GroupLayout PART_SERIAL = structLayout(
        sequenceLayout(2, JAVA_INT).withName("part_id"),
        sequenceLayout(4, JAVA_INT).withName("serial_no"));

    private Layouts() {
    }

    /** Returns the byte offset of a named field of a structure. */
    public static long offset(MemoryLayout layout, String field) {
        return layout.byteOffset(groupElement(field));
    }

    /** Reads an unsigned 32-bit field. */
    public static long u32(MemorySegment segment, MemoryLayout layout, String field) {
        return Integer.toUnsignedLong(segment.get(JAVA_INT, offset(layout, field)));
    }

    /** Reads element {@code index} of an unsigned 32-bit array field. */
    public static long u32(MemorySegment segment, MemoryLayout layout, String field, int index) {
        return Integer.toUnsignedLong(segment.get(JAVA_INT, offset(layout, field) + index * JAVA_INT.byteSize()));
    }

    /** Reads a 64-bit field. */
    public static long i64(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(JAVA_LONG, offset(layout, field));
    }

    /** Reads a character buffer that may fill its space without a terminator. */
    public static String string(MemorySegment chars) {
        int length = 0;
        while (length < chars.byteSize() && chars.get(JAVA_BYTE, length) != 0) {
            length++;
        }
        return new String(chars.asSlice(0, length).toArray(JAVA_BYTE), StandardCharsets.UTF_8);
    }
}
